export function getAvatarForUser(user?: { id?: number; email?: string; avatar_index?: number } | null): AvatarItem {
  if (!user) return NEPAL_AVATARS[0];

  if (typeof user.avatar_index === 'number' && user.avatar_index >= 0 && user.avatar_index < NEPAL_AVATARS.length) {
    return NEPAL_AVATARS[user.avatar_index];
  }

  if (user.id) {
    const idx = Math.abs(user.id) % NEPAL_AVATARS.length;
    return NEPAL_AVATARS[idx];
  }

  if (user.email) {
    let hash = 0;
    for (let i = 0; i < user.email.length; i++) {
      hash = (hash << 5) - hash + user.email.charCodeAt(i);
      hash |= 0;
    }
    const idx = Math.abs(hash) % NEPAL_AVATARS.length;
    return NEPAL_AVATARS[idx];
  }

  return NEPAL_AVATARS[0];
}
